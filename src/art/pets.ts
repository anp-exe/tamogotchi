export function topRow(grid: PixelGrid): number {
  const i = grid.findIndex((row) => /[^.]/.test(row));
  return i < 0 ? 0 : i;
}

export function bottomRow(grid: PixelGrid): number {
  for (let i = grid.length - 1; i >= 0; i--) if (/[^.]/.test(grid[i])) return i;
  return grid.length - 1;
}
